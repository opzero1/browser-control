def inventory():
    """COLLECT_FILE names the saved output of `pytest --collect-only -q` over the reference tests."""
    counts = {}
    for line in Path(os.environ["COLLECT_FILE"]).read_text().splitlines():
        if line.startswith("test_") and "::" in line:
            identifier = line.split("[", 1)[0]
            counts[identifier] = counts.get(identifier, 0) + 1
    functions = []
    for path in sorted(REFERENCE.glob("test_*.py")):
        tree = ast.parse(path.read_text(), filename=str(path))
        for node in tree.body:
            owners = [(None, node)]
            if isinstance(node, ast.ClassDef):
                owners = [(node.name, item) for item in node.body]
            for owner, item in owners:
                if not isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) or not item.name.startswith("test"):
                    continue
                subtests = sum(isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute)
                               and call.func.attr == "subTest" for call in ast.walk(item))
                identifier = f"{path.name}::{owner}::{item.name}" if owner else f"{path.name}::{item.name}"
                functions.append({"id": identifier, "file": path.name, "class": owner, "name": item.name,
                                  "cases": counts.pop(identifier, 0), "subtest_blocks": subtests})
    if counts or any(item["cases"] == 0 for item in functions):
        raise SystemExit(f"collection and AST scan disagree: {sorted(counts)}")
    write_json("../parity/python-inventory.json", {
        "source": "the fast-chrome Python reference (read-only AST scan; case counts from pytest --collect-only)",
        "collected": sum(item["cases"] for item in functions),
        "functions": functions,
    })


