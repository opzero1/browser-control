def ranges(predicate):
    result, start = [], None
    for cp in range(MAX):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            result.append((start, cp - 1))
            start = None
    if start is not None:
        result.append((start, MAX - 1))
    return result


def encode_ranges(items):
    return ",".join(f"{a:x}" if a == b else f"{a:x}-{b:x}" for a, b in items)


def encode_map(mapping):
    return ",".join(f"{cp:x}:" + " ".join(f"{ord(c):x}" for c in value) for cp, value in sorted(mapping.items()))


def ts_module(name, doc, constants):
    lines = ["// Generated by tests/server/fixtures/capture-python.py from CPython "
             f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.", f"// {doc}", ""]
    for key, value in constants:
        lines.append(f"export const {key} =\n  {json.dumps(value)};")
        lines.append("")
    (UNICODE / name).write_text("\n".join(lines))
    print(f"wrote {(UNICODE / name).relative_to(REPO)}")


def generate_idna_tables():
    chars = [chr(cp) for cp in range(MAX)]
    b2 = {}
    for cp, ch in enumerate(chars):
        mapped = stringprep.map_table_b2(ch)
        if mapped != ch:
            b2[cp] = mapped
    prohibited = ranges(lambda cp: any(test(chars[cp]) for test in (
        stringprep.in_table_c12, stringprep.in_table_c22, stringprep.in_table_c3, stringprep.in_table_c4,
        stringprep.in_table_c5, stringprep.in_table_c6, stringprep.in_table_c7, stringprep.in_table_c8,
        stringprep.in_table_c9)))
    decomposition = {}
    for cp, ch in enumerate(chars):
        full = ucd32.normalize("NFKD", ch)
        if full != ch:
            decomposition[cp] = full
    # CPython's 3.2.0 normalization reorders and composes with the current combining classes and composition
    # table (Modules/unicodedata.c nfd_nfkd and nfc_nfkc use _getrecord_ex); only decomposition is versioned.
    combining = {}
    for cp, ch in enumerate(chars):
        value = unicodedata.combining(ch)
        if value:
            combining[cp] = value
    compose = {}
    for cp, ch in enumerate(chars):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        mapping = unicodedata.decomposition(ch)
        if not mapping or mapping.startswith("<"):
            continue
        parts = [chr(int(part, 16)) for part in mapping.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", parts[0] + parts[1]) == ch:
            compose[cp] = parts[0] + parts[1]
    ts_module("idna2003-tables.ts",
              "RFC 3454 stringprep tables B.1, B.2, C.1.2-C.9, D.1 and D.2 from Lib/stringprep.py, and the "
              "decompositions CPython's unicodedata.ucd_3_2_0.normalize uses.", [
                  ("B1", encode_ranges(ranges(lambda cp: stringprep.in_table_b1(chars[cp])))),
                  ("B2", encode_map(b2)),
                  ("PROHIBITED", encode_ranges(prohibited)),
                  ("D1", encode_ranges(ranges(lambda cp: stringprep.in_table_d1(chars[cp])))),
                  ("D2", encode_ranges(ranges(lambda cp: stringprep.in_table_d2(chars[cp])))),
                  ("NFKD_32", encode_map(decomposition)),
                  ("COMBINING", ",".join(f"{cp:x}:{value}" for cp, value in sorted(combining.items()))),
                  ("COMPOSE", encode_map(compose)),
              ])


def generate_case_tables():
    chars = [chr(cp) for cp in range(MAX)]
    lower = {cp: chars[cp].lower() for cp in range(MAX) if chars[cp].lower() != chars[cp] and cp != 0x3A3}
    casefold = {cp: chars[cp].casefold() for cp in range(MAX) if chars[cp].casefold() != chars[cp]}
    # Final_Sigma context classes, probed through str.lower() itself (Objects/unicodeobject.c
    # handle_capital_sigma): a case-ignorable character is skipped; otherwise its casedness decides.
    ignorable = []
    cased = []
    for cp in range(MAX):
        ch = chars[cp]
        before_final = (ch + "\u03a3").lower().endswith("\u03c2")
        after_final = ("A\u03a3" + ch + "A").lower().startswith("a\u03c2")
        if before_final:
            cased.append(cp)
        elif not after_final:
            ignorable.append(cp)
    ignorable_set, cased_set = set(ignorable), set(cased)
    ts_module("casefold-table.ts",
              "Python str.lower(), str.casefold(), str.isspace(), str.isalnum() and the Final_Sigma classes.", [
                  ("LOWER", encode_map(lower)),
                  ("CASEFOLD", encode_map(casefold)),
                  ("SPACE", encode_ranges(ranges(lambda cp: chars[cp].isspace()))),
                  ("ALNUM", encode_ranges(ranges(lambda cp: chars[cp].isalnum()))),
                  ("CASE_IGNORABLE", encode_ranges(ranges(lambda cp: cp in ignorable_set))),
                  ("CASED", encode_ranges(ranges(lambda cp: cp in cased_set))),
              ])


