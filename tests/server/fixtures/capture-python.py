class FakeConnection:
    def __init__(self, responses):
        self.responses = responses
        self.alive = True
        self.calls = []

    def call(self, method, params=None):
        self.calls.append((method, params))
        value = self.responses.get(method)
        if isinstance(value, Exception):
            raise value
        return value

    def close(self):
        self.alive = False


