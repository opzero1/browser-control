def segment(marker, payload):
    return bytes([0xFF, marker]) + (len(payload) + 2).to_bytes(2, "big") + payload


def sof(width, height, layers=3, bits=8, marker=0xC0, extra=b""):
    components = b"".join(bytes([i + 1, 0x11, 0]) for i in range(layers))
    return segment(marker, bytes([bits]) + height.to_bytes(2, "big") + width.to_bytes(2, "big")
                   + bytes([layers]) + components + extra)


