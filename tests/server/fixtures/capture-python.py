def url_record(value):
    record = {"input": value}
    try:
        parts = urlsplit(value)
        split = {"scheme": parts.scheme, "netloc": parts.netloc, "path": parts.path, "query": parts.query,
                 "fragment": parts.fragment, "username": parts.username, "password": parts.password,
                 "hostname": parts.hostname}
        try:
            split["port"] = parts.port
        except ValueError:
            split["port_error"] = True
        record["urlsplit"] = split
    except ValueError:
        record["urlsplit"] = {"error": "ValueError"}
    os.environ.pop("FAST_CHROME_ALLOW_LOOPBACK", None)
    record["origin"] = outcome(native_server.origin, value)
    os.environ["FAST_CHROME_ALLOW_LOOPBACK"] = "1"
    record["origin_loopback"] = outcome(native_server.origin, value)
    os.environ.pop("FAST_CHROME_ALLOW_LOOPBACK", None)
    record["ascii_host"] = outcome(sites.ascii_host, value)
    record["cookie_site"] = outcome(sites.cookie_site, value)
    record["valid_site"] = sites.valid_site(value)
    record["ip_literal"] = sites.ip_literal(value)
    try:
        record["ip_address"] = str(ipaddress.ip_address(value))
    except ValueError:
        record["ip_address"] = None
    return record


